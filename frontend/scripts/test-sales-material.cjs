const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const context = {exports:{}};
const source = fs.readFileSync(path.join(__dirname, '../src/sales-material.ts'), 'utf8');
vm.runInNewContext(ts.transpileModule(source, {compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText, context);
const {primaryNoticeIds, materialRole, noticeLabel} = context.exports;
const project = {main_notice_id:1, main_notice_ids:[1,2,1], correction_notice_ids:[3], notices:[{notice_id:1,title:'访客采购公告'},{notice_id:2,title:'通行采购公告'},{notice_id:3,title:'采购更正'},{notice_id:4,title:'结果公告'}]};
assert.deepEqual(Array.from(primaryNoticeIds(project)), [1,2]);
assert.deepEqual(Array.from(primaryNoticeIds({main_notice_id:7})), [7]);
assert.deepEqual(Array.from(primaryNoticeIds()), []);
assert.equal(materialRole(project, 2), '采购主公告');
assert.equal(materialRole(project, 3), '采购更正');
assert.equal(materialRole(project, 4), '关联公告（未选入本次材料）');
assert.equal(noticeLabel(project, 1), '#1 访客采购公告');
assert.equal(noticeLabel(project, 8), '#8');
console.log('PASS selected material roles, multiple main notices, legacy fallback and evidence labels');
